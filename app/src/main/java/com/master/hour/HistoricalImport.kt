suspend fun importHistoricalData(context: Context, dao: EntryDao) {
    val prefs = context.getSharedPreferences("history_import", Context.MODE_PRIVATE)
    if (prefs.getBoolean("pdf_2026_imported", false)) return
    val parser = SimpleDateFormat("dd.MM.yyyy", Locale("ru")).apply { isLenient = false }
    historicalIncome.forEach { row ->
        val parts = row.split('|')
        val date = parser.parse(parts[0])?.time ?: 0L
        dao.insert(Entry(type = "income", title = parts[1], amount = parts[2].toLong(), createdAt = date, note = "Импортировано из PDF"))
    }
    historicalExpenses.forEach { row ->
        val parts = row.split('|')
        dao.insert(Entry(type = "expense", title = parts[0], amount = parts[1].toLong(), createdAt = 0L, note = "Историческая покупка. Дата в исходном PDF не указана"))
    }
    prefs.edit().putBoolean("pdf_2026_imported", true).apply()
}